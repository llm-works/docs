"""Render the main site's nav partial as the docs header.

The markup, theme switch included, stays the main site's own, with two changes:

- root-relative links point at the main site's origin (an empty origin keeps them
  root-relative, for a local preview served next to the main site);
- a "Docs" item, marked current, follows Platform.

The docs search is not part of the header: it sits above the tree (overrides/main.html).
The output is a Jinja partial for the Zensical theme override.
"""

import re

GENERATED_MARK = "{#- generated by docsite from the main site's partials/nav.html -#}\n"

DOCS_ITEM = '        <li><a href="{{ nav.homepage.url | url }}" aria-current="page">Docs</a></li>\n'

_CURRENT = ' aria-current="page"'
_ROOT_HREF = re.compile(r'href="/(?!/)')


class NavMarkupError(ValueError):
    """The nav partial lacks an anchor the docs header depends on."""


def render_header(nav_html: str, site_origin: str) -> str:
    """Return the docs header partial for the given main-site nav markup."""
    html = nav_html.replace(_CURRENT, "")
    html = _ROOT_HREF.sub(f'href="{site_origin}/', html)
    platform = re.search(rf'.*href="{re.escape(site_origin)}/platform/".*\n', html)
    if not platform:
        raise NavMarkupError("no Platform item in the main site's nav")
    return GENERATED_MARK + html[: platform.end()] + DOCS_ITEM + html[platform.end() :]
